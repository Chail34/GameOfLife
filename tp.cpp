struct GridData {
    // Information to store in the grid's cells
    std::vector<Vec3> vertices ; // Sommets du maillage qui sont dans la cellule
    std::vector<Vec3> normals ; // Normales du maillage qui sont dans la cellule

    Vec3 representant ;

    Vec3 getRepresentant(){
        return representant/vertices.size() ;
    }
    Vec3 getNormal(){
        Vec3 norm = Vec3(0.0,0.0,0.0) ;
        int nbN = normals.size() ;
        for(int i = 0 ; i < nbN ; i++){
            norm += normals[i] ;
        }
        norm.normalize() ;
        return norm ;
    }

};
struct Grid {
    std::vector<GridData> cells;

    Vec3 minPos, maxPos;
    int resolution;

    int getCellX(Vec3 pos) { return resolution * (pos[0] - minPos[0]) / (maxPos[0] - minPos[0]); }
    int getCellY(Vec3 pos) { return resolution * (pos[1] - minPos[1]) / (maxPos[1] - minPos[1]); }
    int getCellZ(Vec3 pos) { return resolution * (pos[2] - minPos[2]) / (maxPos[2] - minPos[2]); }

    int getIndex(int x, int y, int z) { return x * resolution * resolution + y * resolution + z; }
    int getIndex(Vec3 pos) { return getCellX(pos) * resolution * resolution + getCellY(pos) * resolution + getCellZ(pos); }
};

void Mesh::simplify(unsigned int resolution) {
    std::cerr << "Simplification to be done." << std::endl;
    // Compute the cube C that englobes all vertices

    int fullRes = resolution*resolution*resolution ;
    int n = vertices.size() ;

    float x_min = vertices[0][0] ;
    float x_max = vertices[0][0] ;
    float y_min = vertices[0][1] ;
    float y_max = vertices[0][1] ;
    float z_min = vertices[0][2] ;
    float z_max = vertices[0][2] ;
    // Calcul des 2 coordonnées les plus éloignés du cube
    for(int i = 1 ; i < n ; i++){
        float x = vertices[i][0] ;
        float y = vertices[i][1] ;
        float z = vertices[i][2] ;
        if(x < x_min) x_min = x ;
        if(x > x_max) x_max = x ;
        if(y < y_min) y_min = y ;
        if(y > y_max) y_max = y ;
        if(z < z_min) z_min = z ;
        if(z > z_max) z_max = z ;
    }
    // On créer tous les sommets du cube
    // Carré inférieur
    C.push_back(Vec3(x_min-0.1, y_min-0.1, z_min-0.1));
    C.push_back(Vec3(x_max+0.1, y_min-0.1, z_min-0.1));
    C.push_back(Vec3(x_max+0.1, y_max+0.1, z_min-0.1));
    C.push_back(Vec3(x_min-0.1, y_max+0.1, z_min-0.1));
    // Carré supérieur
    C.push_back(Vec3(x_min-0.1, y_min-0.1, z_max+0.1));
    C.push_back(Vec3(x_max+0.1, y_min-0.1, z_max+0.1));
    C.push_back(Vec3(x_max+0.1, y_max+0.1, z_max+0.1));
    C.push_back(Vec3(x_min-0.1, y_max+0.1, z_max+0.1));

    // Create a grid of size resolution x resolution x resolution in the cube

    Grid G ; // Grille de résolution
    G.resolution = resolution ;
    G.minPos = Vec3(x_min-0.1, y_min-0.1, z_min-0.1) ;
    G.maxPos = Vec3(x_max+0.1, y_max+0.1, z_max+0.1) ;

    G.cells.resize(fullRes, GridData()) ; // Le nombre de cellule au total

    // For each vertex, add the position and normal to its representant in the grid
    // (Count the number of vertices per cell)

    int nbCells = G.cells.size() ;

    for(int i = 0 ; i < n ; i++){
        Vec3 v = vertices[i] ;
        Vec3 n = normals[i] ;
        
        int cellID = G.getIndex(v) ;

        G.cells[cellID].representant += v ;
        G.cells[cellID].vertices.push_back(v);
        G.cells[cellID].normals.push_back(n);
    }

    // Calcul du nombre de sommets par cellules :
    float nbV_by_cells = 0. ;
    for(int i = 0 ; i < fullRes ; i++){
        int nbV = G.cells[i].vertices.size() ; // Nombre de sommets dans une cellule
        nbV_by_cells += nbV ;
    }
    nbV_by_cells = nbV_by_cells/(float)fullRes ;
    std::cout << "Nombre moyen de sommets par cellule = " << nbV_by_cells << std::endl ;

    // For each triangle t, set the indices of its vertices to point to representants
    // If 2 vertices share the same representant, remove the triangle

    int nbT = triangles.size() ;

    std::vector<Triangle> lowPoly ;

    for(int i = 0 ; i < nbT ; i++){
        Triangle t = triangles[i] ;

        // On récupère les indices des positions des sommets du triangles
        int id_p0 = t[0] ;
        int id_p1 = t[1] ;
        int id_p2 = t[2] ;

        // On récupère les positions des sommets su triangles
        Vec3 p0 = vertices[id_p0] ;
        Vec3 p1 = vertices[id_p1] ;
        Vec3 p2 = vertices[id_p2] ;

        // On récupères les indices cellules dans lesquelles se trouves les sommets
        int id0 = G.getIndex(p0) ;
        int id1 = G.getIndex(p1) ;
        int id2 = G.getIndex(p2) ;

        // On calcul quels triangles on garde
        if((id0 != id1) && (id0 != id2) && (id1 != id2)){
            // On donne les nouveaux indices au triangle (permettant de récupérer les représentants)
            t[0] = id0 ;
            t[1] = id1 ;
            t[2] = id2 ;

            lowPoly.push_back(t) ; // On ajoute le triangle après l'avoir modifié   
        }
    }

    triangles = lowPoly ; // On remplace notre maillage original par celui calculé

    // Divide the position of each representant by the number of vertices in the cell.
    // Normalize the normals

    std::vector<Vec3> verticesLowPoly ; // Contiendra les représentants de chaque cellule
    std::vector<Vec3> normalsLowPoly ;

    for(int i = 0 ; i < nbCells ; i++){
        GridData gd = G.cells[i] ;
        verticesLowPoly.push_back(gd.getRepresentant());
        normalsLowPoly.push_back(gd.getNormal());
    }

    vertices = verticesLowPoly ;
    normals = normalsLowPoly ;

    // BONUS EXERCICE : Instead of using the mean position of the vertices in the cell,
    // use the QEM proposed in "Out-of-core simplification of large polygonal models."
    // Peter Lindstrom. SIGGRAPH 2000 (http://wwwevasion.imag.fr/people/Franck.Hetroy/Teaching/Geo3D/Articles/lindstrom2000.pdf)
    // You might need to change the content of GridData and the way to process it
}

